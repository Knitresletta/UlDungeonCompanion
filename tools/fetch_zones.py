"""
Build ZoneData.lua from the ForeverChanges world map page.

ForeverChanges (https://foreverchanges.pro/map) lists the level range and
faction territory of every zone as read from the beta client's own files.
The game's C_Map.GetMapLevels answers 0 for every zone on the Forever
client (probe 14.10.2026), so this page is the only machine-readable
source of the ranges Forever itself uses.

    python3 -I tools/fetch_zones.py -o ZoneData.lua            fetch the page and write the file
    python3 -I tools/fetch_zones.py --html map.html -o ZoneData.lua   build from a saved copy

Zones the client has no range for yet ("Not set yet") are listed in a
comment at the end of the file and left out of the table, so nothing is
shown for them in game. Cities are not on the page at all.
"""

import argparse
import datetime
import html
import re
import sys
import urllib.request

SITE = "https://foreverchanges.pro"
USER_AGENT = "UlDungeonCompanion data tool (https://github.com/Knitresletta)"

TERRITORY = {"a": "Alliance", "h": "Horde", "c": "Contested"}

# One entry per zone: a link to the zone's map page followed by the level
# span. The continent lists use <li> rows with a <small> territory label;
# Zephras Isle has a map of its own and appears only as an article heading.
ROW = re.compile(
    r'<a href="(/map/[^"]+)">([^<]+)</a>'
    r'<span class="wm-lv wm-lv-([a-z])">([^<]*)</span>'
)
RANGE = re.compile(r"^\s*(\d+)\s*[–-]\s*(\d+)\s*$")


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request, timeout=30) as response:
        return response.read().decode("utf-8")


def parse(page):
    page = html.unescape(page)
    zones, unset, seen = [], [], set()
    for href, name, cls, span in ROW.findall(page):
        name = name.strip()
        if name in seen:
            continue
        seen.add(name)
        territory = TERRITORY.get(cls, "Contested")
        match = RANGE.match(span)
        if match:
            zones.append((name, int(match.group(1)), int(match.group(2)), territory, href))
        else:
            unset.append((name, span.strip(), href))
    return zones, unset


def lua_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(zones, unset, fetched):
    width = max(len(lua_string(z[0])) for z in zones)
    lines = [
        "-- Zone Data: the level range each zone is meant for and whose",
        "-- territory it is, keyed by the zone's English name as the client",
        "-- reports it (C_Map.GetMapInfo(...).name).",
        "--",
        "-- Generated by tools/fetch_zones.py from the ForeverChanges world map",
        "-- (https://foreverchanges.pro/map), which reads the ranges from the beta",
        "-- client's own files. The client's C_Map.GetMapLevels answers 0 for every",
        "-- zone (probe 14.10.2026), so this is where Forever's own ranges live.",
        "-- Fetched " + fetched + ". Do not edit by hand; rerun the script.",
        "--",
        "-- Names are matched at runtime (ZoneLabels.lua), so no map IDs are hard",
        "-- coded. DungeonData.lua refers to the same names in its zone field.",
        "-- Cities are not listed; nothing is shown for them.",
        "",
        "UlDC.ZONES = {",
    ]
    for name, lo, hi, territory, _ in sorted(zones, key=lambda z: (z[1], z[2], z[0])):
        key = lua_string(name).ljust(width)
        lines.append(f"    [{key}] = {{ levels = {{ {lo}, {hi} }}, territory = {lua_string(territory)} }},")
    lines.append("}")
    if unset:
        lines.append("")
        lines.append("-- Zones the client has no range for yet, left out on purpose:")
        for name, span, _ in unset:
            lines.append(f"--   {name} ({span})")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--html", help="build from a saved copy of the map page instead of fetching")
    parser.add_argument("-o", "--output", default="ZoneData.lua")
    args = parser.parse_args()

    if args.html:
        with open(args.html, encoding="utf-8") as handle:
            page = handle.read()
    else:
        page = fetch(SITE + "/map")
    zones, unset = parse(page)
    if len(zones) < 30:
        sys.exit(f"only {len(zones)} zones parsed; the page layout has probably changed")
    fetched = datetime.date.today().isoformat()
    with open(args.output, "w", encoding="utf-8") as handle:
        handle.write(build(zones, unset, fetched))
    print(f"{len(zones)} zones written to {args.output}, {len(unset)} without a range: "
          + ", ".join(name for name, _, _ in unset))


if __name__ == "__main__":
    main()
